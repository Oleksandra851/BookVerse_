    val quotes: List<Quote> get() = _quotes

    fun addBook(title: String, author: String, totalPages: Int, note: String) {
        _books.add(Book(System.currentTimeMillis().toString(), title, author, 0, totalPages, BookStatus.PLANNED, 0, note))
    }

    fun addQuote(text: String, bookTitle: String, author: String) {
        _quotes.add(Quote(System.currentTimeMillis().toString(), text, bookTitle, author))
    }

    fun deleteBook(id: String) {
        _books.removeIf { it.id == id }
    }

    fun deleteQuote(id: String) {
        _quotes.removeIf { it.id == id }
    }
